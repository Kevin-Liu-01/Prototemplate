type MarkInput = Omit<Mark, 'file' | 'constructionFile' | 'textFile'> & {
  /** the mark has a construction overlay at /marks/<id>-construction.svg */
  overlay?: true;
  /** the mark has its plain characters at /marks/<id>.txt */
  text?: true;
};

function mark({ overlay, text, ...rest }: MarkInput): Mark {
  return {
    ...rest,
    file: `/marks/${rest.id}.svg`,
    ...(overlay ? { constructionFile: `/marks/${rest.id}-construction.svg` } : {}),
    ...(text ? { textFile: `/marks/${rest.id}.txt` } : {}),
  };
}

