/**
 * The marks behind /marks: the speed set for General Translation, seven
 * marks in one register, and the two survivors of the earlier round, each
 * a public SVG in currentColor under public/marks with its thesis,
 * construction and use notes as data. Pure data and types, no React, no
 * DOM, so the server page can read the files and the client viewer can lay
 * them out from the same list.
 *
 * The register comes from a race-type reference Kevin brought: wide
 * letters, a forward slant, one horizontal cut through the letters, and
 * speed bars that lead into the first letter. Every mark is black and
 * white, one color, and takes the ink of whatever it sits on. The seven
 * speed files are generated by scripts/build-speed-marks.mjs (pnpm
 * build:marks) with tight viewBoxes, so the viewer sizes each by height
 * and its own aspect. Two-way and Globe G keep their construction
 * overlays from the earlier round and stand at the end for comparison.
 * The current doubled-line monogram is kept only as REFERENCE_MARK, the
 * memory the marks are measured against, never as a candidate.
 */

/** The two families: the speed register, and the picture marks of the earlier round. */
export type MarkFamily = 'speed' | 'picture';

/** What the mark is: the letters alone, or the letters with the name (or as a rendering of the name). */
export type MarkKind = 'monogram' | 'wordmark';

export type Mark = {
  /** the file stem under public/marks; unique, and what the hash names */
  id: string;
  name: string;
  family: MarkFamily;
  kind: MarkKind;
  /** the mark in one or two sentences */
  thesis: string;
  /** the geometry: units, skew, cuts, faces, how the file is built */
  construction: string;
  /** how it behaves at small sizes and where it goes */
  use: string;
  /** the clean mark, a public path: /marks/<id>.svg */
  file: string;
  /** the construction overlay, a public path, for the marks of the earlier round */
  constructionFile?: string;
  /** the plain characters, a public path, for the ASCII rendering */
  textFile?: string;
};

/** A mark's files as read from disk by the server page, and the aspect of its viewBox (width over height). */
export type MarkArt = { clean: string; construction?: string; aspect: number };

