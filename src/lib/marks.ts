/**
 * The marks behind /marks and every other surface that draws one. The
 * catalog at the end of this file (CATALOG, SHORTLIST, FAMILIES) is what
 * the surfaces read: one row shape for every mark, the shortlist in page
 * order, and the families by the idea each draws. The earlier lists feed
 * it unchanged: the two marks in production (PRODUCTION_MARKS), the
 * hemispheres round (HEMISPHERE_FAMILIES and HEMISPHERE_MARKS), the speed
 * marks of MARKS with MARK_RULES, and the picture marks of MARKS and
 * GLOBE_CONCEPTS from the earlier rounds. The marks from 2026-10-28 on are
 * DYNAMIC_MARKS, finished SVGs under public/marks/dynamic that pnpm
 * import:marks copies in. Every mark is a public SVG in currentColor
 * under public/marks, with its notes as data. Pure data and types, no
 * React, no DOM and no imports, so the server page, the client viewer and
 * the Node tests read the same lists.
 *
 * The speed register comes from a race-type reference Kevin brought: wide
 * letters, a forward slant, one horizontal cut through the letters, and
 * speed bars that lead into the first letter. The seven speed files are
 * generated by scripts/build/speed-marks.mjs (pnpm build:marks) with tight
 * viewBoxes, so the viewer sizes each by height and its own aspect.
 * Kevin's three picks and the six marks of the closed-top round, all in
 * the hemispheres round, have a construction drawing beside their
 * file, <id>-construction.svg: the mark's geometry with each measurement
 * labelled and the arithmetic that places it, drawn by the construction
 * tool of the 2026-10 marks round. Every other mark has none, and its
 * constructionFile is unset. A drawing has a viewBox of its own, at times
 * wider or taller than the mark's, so the server page reads its size from
 * the file. Its labels are set in Inter, which an SVG drawn as an
 * image cannot load, so each label carries a textLength equal to its
 * width in InterVariable, and a browser that falls back to another face
 * keeps every label inside the drawing. REFERENCE_MARK is the
 * doubled-line monogram in production.
 */

/** The two families: the speed register, and the picture marks of the earlier round. */
export type MarkFamily = 'speed' | 'picture';

/** What the mark is: the letters alone, or the letters with the name (or as a rendering of the name). */
export type MarkKind = 'monogram' | 'wordmark';

export type Mark = {
  /** the file stem under public/marks; unique, and what the hash names */
  id: string;
  name: string;
  family: MarkFamily;
  kind: MarkKind;
  /** the mark in one or two sentences */
  thesis: string;
  /** the geometry: units, skew, cuts, faces, how the file is built */
  construction: string;
  /** how it behaves at small sizes and where it goes */
  use: string;
  /** the clean mark, a public path: /marks/<id>.svg */
  file: string;
  /** the construction drawing, when the mark has one, a public path: /marks/<id>-construction.svg */
  constructionFile?: string;
  /** the plain characters, a public path, for the ASCII rendering */
  textFile?: string;
  /** the mark's motion piece: a film built on the mark alone, its web copy and poster under public/media */
  film?: MarkFilm;
};

/** A film made from one mark, played in that mark's section of /marks. */
export type MarkFilm = { name: string; summary: string; length: string; src: string; poster: string };

/** One rule of the register; the first section lists them as ruled rows. */
