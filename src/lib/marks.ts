/** Every mark /marks shows, the earlier lists first and then the dynamic marks; ids are unique across it. */
export const CATALOG: readonly CatalogMark[] = [...earlierRows(), ...DYNAMIC_MARKS];

const BY_ID = new Map(CATALOG.map((mark) => [mark.id, mark]));

/** A mark of the catalog by its id. */
export function catalogMark(id: string): CatalogMark | undefined {
  return BY_ID.get(id);
}

/** The shortlist's marks in SHORTLIST's order. */
export function shortlist(): readonly CatalogMark[] {
  return SHORTLIST.flatMap((id) => BY_ID.get(id) ?? []);
}

/**
 * The marks /brand's badge cuts through after the GT monogram: the first
 * four shortlisted marks whose drawn box is no wider than `aspect`, the
 * monogram's width over its height, so the monogram sets the badge's
 * width and the box holds still.
 */
export function badgeMarks(aspect: number): readonly CatalogMark[] {
  return shortlist()
    .filter((mark) => mark.box && mark.box[2] / mark.box[3] <= aspect)
    .slice(0, 4);
}

/** A family's record. */
export function familyRow(id: MarkFamilyId): MarkFamilyRow {
  return FAMILIES.find((family) => family.id === id) ?? (FAMILIES[0] as MarkFamilyRow);
}

/**
 * A family's dynamic marks in page order: its shortlisted marks in
 * SHORTLIST's order, so the family opens with the best of it by Kevin's
 * verdicts, then the drawings it grew from, then the rest as
 * DYNAMIC_MARKS lists them.
 */
export function dynamicFamily(id: MarkFamilyId): readonly CatalogMark[] {
  const marks = DYNAMIC_MARKS.filter((mark) => mark.family === id);
  const rank = (mark: CatalogMark) => {
    const at = SHORTLIST.indexOf(mark.id);
    return at >= 0 ? at : SHORTLIST.length + (mark.opens ? 0 : 1);
  };
  return marks
    .map((mark, i) => ({ mark, i }))
    .sort((a, b) => rank(a.mark) - rank(b.mark) || a.i - b.i)
    .map(({ mark }) => mark);
}

/**
 * Every graticule mark, the catalog rows whose id starts with graticule-,
 * in the order /marks/graticule draws them: the shortlisted ones in
 * SHORTLIST's order, then the other picks, then the rest, each group as
 * DYNAMIC_MARKS lists it.
 */
export function graticuleMarks(): readonly CatalogMark[] {
  const rank = (mark: CatalogMark) => {
    const at = SHORTLIST.indexOf(mark.id);
    return at >= 0 ? at : SHORTLIST.length + (mark.pick ? 0 : 1);
  };
  return DYNAMIC_MARKS.filter((mark) => mark.id.startsWith('graticule-'))
    .map((mark, i) => ({ mark, i }))
    .sort((a, b) => rank(a.mark) - rank(b.mark) || a.i - b.i)
    .map(({ mark }) => mark);
}

/** The mark a family leads with, drawn large on both grounds before the rest: its first mark in page order. */
export function familyLead(id: MarkFamilyId): CatalogMark | undefined {
  return dynamicFamily(id)[0];
}

/**
 * The families in page order: a family with a shortlisted mark takes the
 * place of its best one; the rest follow, the most recently engaged
 * first; In production closes the page.
 */
export function pageFamilies(): readonly MarkFamilyRow[] {
  const best = (family: MarkFamilyRow) => {
    const places = SHORTLIST.map((id, i) => (BY_ID.get(id)?.family === family.id ? i : -1)).filter((i) => i >= 0);
    return places.length ? Math.min(...places) : Number.POSITIVE_INFINITY;
  };
  const rest = FAMILIES.filter((family) => family.id !== 'production');
  const ranked = rest.filter((family) => Number.isFinite(best(family))).sort((a, b) => best(a) - best(b));
  const others = rest
    .filter((family) => !Number.isFinite(best(family)))
    .map((family, i) => ({ family, i }))
    .sort((a, b) => b.family.engaged.localeCompare(a.family.engaged) || a.i - b.i)
    .map(({ family }) => family);
  return [...ranked, ...others, familyRow('production')];
}

/** The square every dynamic mark is drawn on. */
export const MARK_UNITS = 256;

const percent = (v: number) => `${Math.round(v * 10000) / 100}%`;

/**
 * The CSS mask size and position that show only a mark's drawn box of its
 * 256 unit file: the file scaled so the box fills the element, and shifted
 * so the box's corner sits on the element's. Percentages, so the crop
 * holds at any size, as long as the element takes the box's aspect.
 */
export function boxMask(box: readonly [number, number, number, number]): { size: string; position: string; aspect: number } {
  const [x, y, w, h] = box;
  const along = (offset: number, span: number) => (Math.abs(MARK_UNITS - span) < 1e-6 ? 0 : offset / (MARK_UNITS - span));
  return {
    size: `${percent(MARK_UNITS / w)} ${percent(MARK_UNITS / h)}`,
    position: `${percent(along(x, w))} ${percent(along(y, h))}`,
    aspect: w / h,
  };
}
