  mode?: 'fill' | 'outline' | 'glow';
  /** Band half-width in grid cells when mode is 'outline'. Default 6. */
  outlineWidth?: number;
  /** Distance in grid cells over which 'glow' decays. Default 60. */
  glowRadius?: number;
