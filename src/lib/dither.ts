export type GlyphField = FieldFn & {
  /** Signed distance in grid cells at (u, v): negative inside the glyph. */
  signedDistance: (u: number, v: number) => number;
  /** Grid resolution actually used. */
  resolution: number;
};

/**
 * Build a signed-distance field from a letterform so type can be dithered.
 *
 * Rasterises the glyph once into an offscreen canvas, then runs an exact
 * Euclidean distance transform over the inside and the outside separately and
 * subtracts them. That gives a true signed distance, which is what makes the
 * result resolution-independent: the field can be sampled at any dither scale
 * and the edge ramp stays the same *visual* width, and modes like outline and
 * glow are then one-line functions of the distance.
 *
 * The alternative — sampling the rasterised alpha directly — only ever gives
 * you a 1-pixel-wide edge gradient, so at dither scale 3 the letterform's
 * contour aliases into hard jaggies with nothing for the ordered pattern to
 * articulate.
 *
 * Must run in a DOM environment. Call after `document.fonts.ready` if the
 * letterform depends on a webfont, otherwise the metrics come from the
 * fallback family.
 */
export function makeGlyphField(opts: GlyphFieldOptions): GlyphField {
  const {
    text,
    font = '900 {size}px ui-sans-serif, system-ui, sans-serif',
    resolution = 256,
    softness = 14,
    mode = 'fill',
    outlineWidth = 6,
    glowRadius = 60,
    padding = 0.06,
    tracking = 0,
    fit = 'contain',
    aspect = 1,
  } = opts;

  const size = Math.max(8, Math.floor(resolution));
  const inside = new Float64Array(size * size);

  // --- rasterise -------------------------------------------------------
  const mask = new Uint8Array(size * size);
  if (typeof document !== 'undefined') {
    const raster = document.createElement('canvas');
    raster.width = size;
    raster.height = size;
    const ctx = raster.getContext('2d', { willReadFrequently: true });
    if (ctx) {
      ctx.clearRect(0, 0, size, size);
      ctx.fillStyle = '#fff';
      ctx.textAlign = 'center';
      ctx.textBaseline = 'alphabetic';
      if (tracking !== 0) {
        // letterSpacing is not in older lib.dom typings; feature-detect.
        const withSpacing = ctx as CanvasRenderingContext2D & {
          letterSpacing?: string;
        };
        if ('letterSpacing' in withSpacing) {
          withSpacing.letterSpacing = `${tracking}em`;
        }
      }

      const usable = size * (1 - padding * 2);

      // Binary-search the font size that makes the glyph's tight ink box fill
      // the usable area. Measuring beats guessing from em size: display faces
      // vary wildly in cap height and overshoot.
      const setFont = (px: number) => {
        ctx.font = font.includes('{size}')
          ? font.replace('{size}', String(px))
          : `${px}px ${font}`;
      };
      const inkBox = (px: number) => {
        setFont(px);
        const m = ctx.measureText(text);
        const w =
          (m.actualBoundingBoxLeft ?? 0) + (m.actualBoundingBoxRight ?? 0);
        const h =
          (m.actualBoundingBoxAscent ?? 0) + (m.actualBoundingBoxDescent ?? 0);
        return { w: w || m.width, h: h || px, m };
      };

      let px = usable;
      for (let iter = 0; iter < 24; iter++) {
        const { w, h } = inkBox(px);
        const scale = Math.min(usable / (w || 1), usable / (h || 1));
        if (Math.abs(scale - 1) < 0.002) break;
        px = Math.max(4, Math.min(size * 8, px * scale));
      }

      const { m } = inkBox(px);
      const ascent = m.actualBoundingBoxAscent ?? px * 0.7;
      const descent = m.actualBoundingBoxDescent ?? 0;
      const left = m.actualBoundingBoxLeft ?? 0;
      const right = m.actualBoundingBoxRight ?? m.width;
      // Centre the tight INK box, not the advance box — side bearings and
      // overshoot would otherwise push the glyph off-centre.
      //
      // textAlign is 'center', so the anchor is already the centre of the
      // advance box and the bounding-box metrics are measured relative to it:
      // the ink spans [anchor - left, anchor + right]. Its centre therefore
      // sits at anchor + (right - left) / 2, so to land that centre on the
      // grid centre the anchor goes to size/2 - (right - left)/2. Adding
      // `left` on top of this (the correct term for textAlign 'left') shifts
      // the glyph right by half its width and clips it.
      ctx.fillText(
        text,
        size / 2 - (right - left) / 2,
        size / 2 + (ascent - descent) / 2
      );

      const data = ctx.getImageData(0, 0, size, size).data;
      for (let i = 0, p = 3; i < mask.length; i++, p += 4) {
        mask[i] = (data[p] ?? 0) >= 128 ? 1 : 0;
      }
    }
  }

  // --- exact Euclidean distance transform -------------------------------
  // Felzenszwalb & Huttenlocher: the squared EDT is separable, and each 1D
  // pass is the lower envelope of a set of parabolas, computable in O(n).
  const INF = 1e20;

  const edt1d = (f: Float64Array, n: number, d: Float64Array) => {
    const vtx = new Int32Array(n);
    const z = new Float64Array(n + 1);
    let k = 0;
    vtx[0] = 0;
    z[0] = -INF;
    z[1] = INF;
    for (let q = 1; q < n; q++) {
      let s =
        (f[q]! + q * q - (f[vtx[k]!]! + vtx[k]! * vtx[k]!)) /
        (2 * q - 2 * vtx[k]!);
      while (s <= z[k]!) {
        k--;
        s =
          (f[q]! + q * q - (f[vtx[k]!]! + vtx[k]! * vtx[k]!)) /
          (2 * q - 2 * vtx[k]!);
      }
      k++;
      vtx[k] = q;
      z[k] = s;
      z[k + 1] = INF;
    }
    k = 0;
    for (let q = 0; q < n; q++) {
      while (z[k + 1]! < q) k++;
      const dq = q - vtx[k]!;
      d[q] = dq * dq + f[vtx[k]!]!;
    }
  };

  /** Squared EDT of the set where `isSeed(i)` is true. */
  const edt2d = (isSeed: (i: number) => boolean): Float64Array => {
    const grid = new Float64Array(size * size);
    for (let i = 0; i < grid.length; i++) grid[i] = isSeed(i) ? 0 : INF;

    const line = new Float64Array(size);
    const out = new Float64Array(size);

    // Columns.
    for (let x = 0; x < size; x++) {
      for (let y = 0; y < size; y++) line[y] = grid[y * size + x]!;
      edt1d(line, size, out);
      for (let y = 0; y < size; y++) grid[y * size + x] = out[y]!;
    }
    // Rows.
    for (let y = 0; y < size; y++) {
      const base = y * size;
      for (let x = 0; x < size; x++) line[x] = grid[base + x]!;
      edt1d(line, size, out);
      for (let x = 0; x < size; x++) grid[base + x] = out[x]!;
    }
    return grid;
  };

  const distOutside = edt2d((i) => mask[i] === 1); // distance to ink
  const distInside = edt2d((i) => mask[i] === 0); // distance to paper

  // Signed distance in grid cells: negative inside the glyph.
  for (let i = 0; i < inside.length; i++) {
    inside[i] =
      mask[i] === 1 ? -Math.sqrt(distInside[i]!) : Math.sqrt(distOutside[i]!);
  }

  /**
   * Bilinear sample of the SDF, so it stays smooth at any dither scale.
   *
   * Under 'contain' the square grid is inset into the (possibly non-square)
   * field box, which leaves field space outside the grid. Rather than cutting
   * the distance off there — which would slice a hard straight edge through a
   * glow halo — the sample is clamped to the grid edge and the distance to the
   * grid boundary is added back. The result stays monotonic and continuous, so
   * outward ramps keep falling off correctly past the grid.
   */
  const sampleSDF = (u: number, v: number): number => {
    let su = u;
    let sv = v;
    if (fit === 'contain') {
      // Inset the square grid into the box's shorter axis.
      if (aspect >= 1) su = (u - 0.5) * aspect + 0.5;
      else sv = (v - 0.5) / aspect + 0.5;
    }

    // How far outside the grid we are, in normalised units.
    const ox = su < 0 ? -su : su > 1 ? su - 1 : 0;
    const oy = sv < 0 ? -sv : sv > 1 ? sv - 1 : 0;
    const outside =
      ox === 0 && oy === 0 ? 0 : Math.sqrt(ox * ox + oy * oy) * (size - 1);

    const gx = clamp01(su) * (size - 1);
    const gy = clamp01(sv) * (size - 1);

    const x0 = Math.floor(gx);
    const y0 = Math.floor(gy);
    const x1 = Math.min(size - 1, x0 + 1);
    const y1 = Math.min(size - 1, y0 + 1);
    const fx = gx - x0;
    const fy = gy - y0;
    const a = inside[y0 * size + x0]!;
    const b = inside[y0 * size + x1]!;
    const c = inside[y1 * size + x0]!;
    const d = inside[y1 * size + x1]!;
    const top = a + (b - a) * fx;
    const bottom = c + (d - c) * fx;
    return top + (bottom - top) * fy + outside;
  };

  const evaluate: FieldFn = (u, v) => {
    const sd = sampleSDF(u, v);

    if (mode === 'outline') {
      // Band centred on the contour: 1 on the line, ramping to 0 either side.
      const band = Math.abs(sd) - outlineWidth;
      return 1 - smoothstep(-softness * 0.5, softness * 0.5, band);
    }
    if (mode === 'glow') {
      // Solid inside, decaying outward — a halo the dither thins out.
      if (sd <= 0) return 1;
      return 1 - smoothstep(0, glowRadius, sd);
    }
    // 'fill': solid inside with a soft fringe straddling the outline, which
    // is what gives the letterform a dithered edge instead of a hard one.
    return 1 - smoothstep(-softness * 0.5, softness * 0.5, sd);
  };

  return Object.assign(evaluate, {
    signedDistance: sampleSDF,
    resolution: size,
  });
}

/* ------------------------------------------------------------------------ *
 * Combinators — fields are just functions, so they compose.
 * ------------------------------------------------------------------------ */

/** Multiply fields together (intersection / masking). */
export function multiplyFields(...fields: FieldFn[]): FieldFn {
  return (u, v, t) => {
    let out = 1;
    for (let i = 0; i < fields.length; i++) out *= fields[i]!(u, v, t);
    return out;
  };
}

/** Take the maximum of fields (union). */
export function maxFields(...fields: FieldFn[]): FieldFn {
  return (u, v, t) => {
    let out = 0;
    for (let i = 0; i < fields.length; i++) {
      const value = fields[i]!(u, v, t);
      if (value > out) out = value;
    }
    return out;
  };
}

/** Linear blend between two fields. */
export function mixFields(a: FieldFn, b: FieldFn, amount: number): FieldFn {
  return (u, v, t) => {
    const av = a(u, v, t);
    return av + (b(u, v, t) - av) * amount;
  };
}

/** Remap a field's output through a scalar function. */
export function mapField(
  field: FieldFn,
  transform: (value: number) => number
): FieldFn {
  return (u, v, t) => transform(field(u, v, t));
}
